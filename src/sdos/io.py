"""Reading and writing matrices and spectra.

Supported matrix inputs: triplet text files ``i j Re(A_ij) [Im(A_ij)]`` (0- or 1-based, one
triangle or both, auto-detected or set by flag), Matrix Market (``.mtx``/``.mm``), and SciPy
``.npz`` files written by ``scipy.sparse.save_npz``.
"""

import sys

import numpy as np
import scipy.sparse as sp

from .operators import check_hermitian


def _assemble(rows, cols, vals, n, storage, hermitian_tol, verbose, label, base_used):
    """Build the full Hermitian CSR matrix from entries (shared by all formats)."""
    upper = np.any(rows < cols)
    lower = np.any(rows > cols)
    if storage == "auto":
        storage = "full" if (upper and lower) else "triangle"
    T = sp.coo_matrix((vals, (rows, cols)), shape=(n, n)).tocsr()
    T.sum_duplicates()
    if storage == "triangle":
        if upper and lower:
            raise ValueError("storage='triangle' given, but entries found in both triangles")
        d = T.diagonal()
        if np.iscomplexobj(d) and np.any(np.abs(d.imag) > 1e-12 * max(1.0, np.abs(d).max())):
            print("warning: diagonal has imaginary parts; they are discarded", file=sys.stderr)
        H = T + T.conj().T - sp.diags(d)
        H = H.tocsr()
        if np.iscomplexobj(H.data):
            H.setdiag(np.real(d))
    else:
        H = T
        herm_err = abs(H - H.conj().T).max() if H.nnz else 0.0
        scale = abs(H).max() if H.nnz else 1.0
        if herm_err > hermitian_tol * scale:
            print(f"warning: full-storage matrix is not Hermitian (max |H-H^+| = {herm_err:.3e}); "
                  "using (H+H^+)/2", file=sys.stderr)
            H = 0.5 * (H + H.conj().T)
    H = H.tocsr()
    H.eliminate_zeros()
    if np.iscomplexobj(H.data) and np.all(H.data.imag == 0):
        H = H.real.tocsr()
    if verbose:
        print(f"read {label}: N = {n}, nnz = {H.nnz}, storage = {storage}, "
              f"index base = {base_used}, {'complex' if np.iscomplexobj(H.data) else 'real'}")
    return H


def read_matrix(path, base="auto", storage="auto", verbose=True, hermitian_tol=1e-10, fmt="auto"):
    """Read a matrix file and return a full Hermitian CSR matrix.

    ``fmt``: 'auto' (from extension / first line), 'triplet', 'mm' or 'npz'.
    ``storage``: 'auto', 'triangle' (the other triangle is generated by conjugation) or 'full'.
    """
    path = str(path)
    if fmt == "auto":
        if path.endswith(".npz"):
            fmt = "npz"
        else:
            with open(path, "r") as f:
                fmt = "mm" if f.readline().startswith("%%MatrixMarket") else "triplet"

    if fmt == "npz":
        A = sp.coo_matrix(sp.load_npz(path))
        return _assemble(A.row.astype(np.int64), A.col.astype(np.int64), A.data, A.shape[0],
                         "full" if storage == "auto" else storage, hermitian_tol, verbose, path, 0)

    if fmt == "mm":
        import scipy.io
        with open(path, "r") as f:
            first = f.readline().lower()
        try:
            A = sp.coo_matrix(scipy.io.mmread(path, spmatrix=True))
        except TypeError:          # SciPy < 1.12 has no spmatrix argument
            A = sp.coo_matrix(scipy.io.mmread(path))
        # NOTE: mmread already expands 'symmetric' / 'hermitian' storage to the full matrix.
        # (The original sdos.py then treated it as a single triangle and failed.)
        expanded = "symmetric" in first or "hermitian" in first
        st = "full" if (expanded and storage == "auto") else storage
        return _assemble(A.row.astype(np.int64), A.col.astype(np.int64), A.data, A.shape[0],
                         st, hermitian_tol, verbose, path, 0)

    data = np.loadtxt(path, comments=("#", "%", "!"), ndmin=2)
    if data.shape[1] < 3:
        raise ValueError("need at least 3 columns: i j Re(A_ij) [Im(A_ij)]")
    rows = data[:, 0].astype(np.int64)
    cols = data[:, 1].astype(np.int64)
    vals = data[:, 2].astype(np.float64)
    if data.shape[1] >= 4:
        im = data[:, 3]
        if np.any(im != 0.0):
            vals = vals + 1j * im
    base_used = (0 if min(rows.min(), cols.min()) == 0 else 1) if base == "auto" else int(base)
    rows = rows - base_used
    cols = cols - base_used
    n = int(max(rows.max(), cols.max())) + 1
    return _assemble(rows, cols, vals, n, storage, hermitian_tol, verbose, path, base_used)


def write_triplets(A, path, triangle="upper", base=1, header="matrix"):
    """Write a (Hermitian) sparse matrix as triplets; ``triangle`` is 'upper', 'lower' or 'full'."""
    T = {"upper": sp.triu, "lower": sp.tril}.get(triangle, lambda x: x)(sp.csr_matrix(A)).tocoo()
    with open(path, "w") as f:
        f.write(f"# {header}\n")
        for i, j, v in zip(T.row, T.col, T.data):
            if np.iscomplexobj(T.data):
                f.write(f"{i + base} {j + base} {v.real:.15e} {v.imag:.15e}\n")
            else:
                f.write(f"{i + base} {j + base} {v:.15e}\n")


def write_dos(path, res, extra_header=""):
    """Write a DOS result as text: E, rho, rho_err, IDOS, IDOS_err."""
    header = (extra_header + "\n" if extra_header else "") + \
        "E   rho(E) [per orbital, integrates to 1]   err   IDOS(E) [fraction]   err"
    np.savetxt(path, np.column_stack([res["E"], res["rho"], res["rho_err"], res["idos"], res["idos_err"]]),
               header=header, fmt="%.10e")
